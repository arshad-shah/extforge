/**
 * Compiles the generated `.extforge/modules.d.ts` (a script file, not a
 * module) together with code that calls `t()`, using the real TypeScript
 * compiler. Unit tests of the codegen string can't catch a declaration that
 * shadows `extforge/i18n` instead of extending it; this can.
 */
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import ts from 'typescript';
import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { generateDts } from '../src/core/i18n/codegen.js';
import { flattenMessages } from '../src/core/i18n/parser.js';

function diagnostics(dir: string, usage: string): string[] {
  const dts = join(dir, 'modules.d.ts');
  const file = join(dir, 'usage.ts');
  writeFileSync(
    dts,
    `// Generated by ExtForge modules. Do not edit by hand.\n\n${generateDts(
      flattenMessages({ popup: { title: 'Hello', greeting: 'Hi, $1! You have $2 tabs.' } }),
    )}\n`,
  );
  writeFileSync(file, usage);
  const program = ts.createProgram([dts, file], {
    strict: true,
    noEmit: true,
    target: ts.ScriptTarget.ES2022,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    skipLibCheck: true,
    baseUrl: dir,
    paths: { 'extforge/i18n': [resolve('src/core/i18n/index.ts')] },
  });
  return ts
    .getPreEmitDiagnostics(program)
    .filter((d) => d.file?.fileName === file)
    .map((d) => ts.flattenDiagnosticMessageText(d.messageText, '\n'));
}

describe('generated i18n types, compiled', () => {
  let dir: string;
  beforeEach(() => {
    dir = mkdtempSync(join(tmpdir(), 'extforge-i18n-tsc-'));
  });
  afterEach(() => rmSync(dir, { recursive: true, force: true }));

  it('lets valid t() calls compile', () => {
    expect(
      diagnostics(
        dir,
        [
          "import { t } from 'extforge/i18n';",
          "export const a: string = t('popup.title');",
          "export const b: string = t('popup.greeting', ['Sam', '3']);",
        ].join('\n'),
      ),
    ).toEqual([]);
  });

  it('rejects unknown keys and wrong substitution counts', () => {
    const errors = diagnostics(
      dir,
      [
        "import { t } from 'extforge/i18n';",
        "t('popup.nope');",
        "t('popup.greeting', ['Sam']);",
        "t('popup.title', ['x']);",
      ].join('\n'),
    );
    expect(errors).toHaveLength(3);
  });
});
